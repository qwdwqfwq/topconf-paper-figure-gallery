import assert from 'node:assert/strict';
import {layoutEditableText} from './editable-text-layout.mjs';
const measureText=s=>s.length*10;
const exact=layoutEditableText('Complete word',{fontSize:20,w:130,h:20,measureText});
assert.equal(exact.fontSize,20);assert.equal(exact.text,'Complete word');
const small=layoutEditableText('Complete word',{fontSize:20,w:120,h:20,measureText});
assert.ok(small.fontSize<20&&small.fontSize>=17);assert.equal(small.overflow,false);
const crowded=layoutEditableText('Complete word',{fontSize:20,w:40,h:20,measureText});
assert.equal(crowded.fontSize,17);assert.equal(crowded.overflow,true);assert.equal(crowded.text,'Complete word');
const lines=layoutEditableText('  First line\r\nSecond line  ',{fontSize:20,w:500,h:50,measureText});
assert.equal(lines.text,'  First line\nSecond line  ');assert.equal(lines.fontSize,20);
assert.equal(layoutEditableText('x',{fontSize:6,w:1,h:1,measureText}).fontSize,6);
const inkMetrics=()=>({width:2196,actualBoundingBoxAscent:48,actualBoundingBoxDescent:14});
const title=layoutEditableText('Title',{fontSize:72,w:2196,h:63,measureText:inkMetrics});
assert.equal(title.fontSize,72,'visible lettering fits without an extra em-height shrink');
assert.equal(title.measuredHeight,62);
const multiline=layoutEditableText('Title\nSubtitle',{fontSize:72,w:2196,h:145,measureText:inkMetrics});
assert.equal(multiline.fontSize,72,'multiple lines retain the original baseline spacing');
assert.ok(Math.abs(multiline.measuredHeight-144.08)<1e-9);
const clipped=layoutEditableText('Title',{fontSize:72,w:2196,h:40,measureText:inkMetrics});
assert.equal(clipped.overflow,true,'actual ink overflow still requires review');
console.log('PASS complete text and explicit lines preserved, modest fitting and overflow detection');
