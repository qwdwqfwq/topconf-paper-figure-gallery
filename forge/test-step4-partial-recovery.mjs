import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import * as core from './reconstruction-core.mjs';
const html=fs.readFileSync(new URL('./index.html',import.meta.url),'utf8');
const source=html.slice(html.indexOf('async function reconstructCatalogWithFallback('),html.indexOf('function reconstructionProgressText('));
const context=vm.createContext({...core,document:{createElement:()=>({getContext:()=>({drawImage(){}}),toDataURL:()=> 'crop'})},compareEditableRender:()=>{},isRecoverableReconstructionError:e=>!!e.visionTimeout});
vm.runInContext(source,context);
const run=context.reconstructCatalogWithFallback;
const canvas={width:1400,height:700};
const scene={canvas:{width:1400,height:700},nodes:[100,1000].map((x,i)=>({id:String(i),type:'rect',x,y:100,w:100,h:100,fill:'#ffffff'}))};
const audit=()=>({tiles:[],fallbackTiles:0});
const quality=(c,s)=>{const n=s.nodes.filter(x=>x.fill==='#000000').length;return Object.fromEntries(['score','darkRecall','localRecall','edgeF1','colorSimilarity'].map(k=>[k,.5+n*.2]));};
const refined=a=>({...a.detailCatalog,nodes:a.detailCatalog.nodes.map(n=>({...n,fill:'#000000'}))});
let calls=0;
await assert.rejects(()=>run(canvas,'src',async()=>{calls++;throw Error('whole failed');},audit(),null,false,quality),/whole failed/);
assert.equal(calls,1);
calls=0;
await assert.rejects(()=>run(canvas,'src',async(s,w,h,a)=>{calls++;if(a.wholeImage)return scene;throw Error('omission failed');},audit(),null,false,quality),/整图查漏未完成/);
assert.equal(calls,2);
const partial=audit();let delayedFinished=false;
const result=await run(canvas,'src',async(s,w,h,a)=>{
 if(a.wholeImage)return scene;if(a.omissionCheck)return {nodes:[]};
 if(a.detailCatalog.nodes.some(n=>n.id==='whole_1'))throw Error('terminal crop failure');
 await new Promise(r=>setTimeout(r,20));delayedFinished=true;return refined(a);
},partial,null,false,quality);
assert.ok(delayedFinished);assert.equal(result.nodes[1].fill,'#000000');assert.equal(partial.failedTiles.length,1);assert.equal(partial.tilePassComplete,false);
const cached=core.createWholeImageCatalog(scene), retry={...audit(),cachedDetailComplete:true};let cropCalls=0;
await run(canvas,'src',async(s,w,h,a)=>{cropCalls++;return refined(a);},retry,cached,true,quality);
assert.equal(cropCalls,2,'low-quality completed cache must be refined again');
const high={...audit(),cachedDetailComplete:true};
await run(canvas,'src',async()=>{throw Error('must not call');},high,cached,true,()=>({score:1,darkRecall:1,localRecall:1,edgeF1:1,colorSimilarity:1}));
assert.equal(high.strategy,'cached-catalog');
const rejected=audit();
await run(canvas,'src',async(s,w,h,a)=>a.wholeImage?scene:a.omissionCheck?{nodes:[]}:refined(a),rejected,null,false,()=>({score:.5,darkRecall:.5,localRecall:.5,edgeF1:.5,colorSimilarity:.5}));
assert.equal(rejected.tilePassComplete,false);assert.equal(rejected.rejectedTiles,2);
const split=audit();
const splitResult=await run(canvas,'src',async(s,w,h,a)=>{
 if(a.wholeImage)return scene;if(a.omissionCheck)return {nodes:[]};
 if(a.depth===0&&a.tile===1)throw Object.assign(Error('timeout'),{visionTimeout:true});
 return refined(a);
},split,null,false,quality);
assert.equal(split.fallbackTiles,1);assert.equal(splitResult.nodes.filter(n=>n.fill==='#000000').length,2);
console.log('PASS: whole/omission gates, partial recovery, adaptive subdivision, cache retry, quality rejection');
