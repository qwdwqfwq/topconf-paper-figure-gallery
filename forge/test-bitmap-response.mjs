import assert from 'node:assert/strict';
import {recoverBitmapResponse,visibleEditableContent} from './bitmap-response.mjs';
import {extractEditableNodes} from './reconstruction-core.mjs';
import {guardPatch,normalizeInventory} from './bitmap-evidence.mjs';

const node={id:'ok',type:'text',x:10,y:10,w:100,h:30,text:'Visible',fill:'#000000'};
assert.equal(recoverBitmapResponse(JSON.stringify([node]),'scene').nodes.length,1);
const damaged='{"regions":[{"type":"rect","x":0,"y":0,"w":200,"h":100}],"nodes":['+JSON.stringify(node)+',{"id":"bad","type":"rect","rx":fill},{"id":"last","type":"rect","x":123,"y":1,"w":5,"h":5,"fill":"#000"}]}';
const scene=recoverBitmapResponse(damaged,'scene');
assert.deepEqual(scene.nodes.map(n=>n.id),['ok','last']);
assert.equal(scene.nodes[1].x,123);
assert.equal(scene.recovery.rejected.length,1);
assert.throws(()=>extractEditableNodes({regions:[{type:'rect',x:0,y:0,w:200,h:100}]}),/without an editable nodes array/);
const item={id:'a',kind:'text',description:'label',x:0,y:0,w:10,h:10,colors:[]};
const inventory=recoverBitmapResponse('{"items":['+JSON.stringify(item).slice(0,-1)+',"panelId="central"}],"layers":[],"connections":[],"uncertainties":[]}','inventory');
assert.equal(inventory.items.length,1);assert.equal(inventory.items[0].panelId,'central');
assert.equal(inventory.recovery.repaired.length,1);
assert.equal(normalizeInventory({...inventory,items:[...inventory.items,{id:'broken'}]},200,100).items.length,1);
const patch=recoverBitmapResponse('{"operations":[{"op":"add","node":{"type":"polyline","points":[[0,0],[1,1]]","closed":true}},{"op":"delete","id":"foreign"}],"uncertainties":[]}','patch');
assert.equal(patch.operations.length,2);assert.equal(patch.recovery.repaired.length,1);
// Real-response failure: repairing fill= must not eat valid formula quotes.
const formulas=['A{T} = {r} ∪ {current leaves}','π_{t+1}','max{1, k_*}','text [0, 1]','escaped "quote" and \\ path }'];
const formulaNodes=formulas.map((text,i)=>({...node,id:'formula-'+i,text}));
const damagedFormulas=JSON.stringify({nodes:[{id:'background',type:'rect',fill:'#ffffff'},...formulaNodes]}).replace('"fill":"#ffffff"','"fill="#ffffff"');
const recoveredFormulas=recoverBitmapResponse(damagedFormulas,'scene');
assert.deepEqual(recoveredFormulas.nodes.slice(1),formulaNodes);
assert.equal(recoveredFormulas.recovery.rejected.length,0);
assert.deepEqual(recoveredFormulas.recovery.repaired,[{reason:'property separator',key:'fill'}]);
const mixedPatch=recoverBitmapResponse('{"operations":[{"op":"add","node":{"type":"polyline","points":[[0,0],[1,1]]","text":'+JSON.stringify(formulas[4])+'}},{"op":"add","node":'+JSON.stringify(formulaNodes[0])+'}]}','patch');
assert.equal(mixedPatch.operations.length,2);
assert.equal(mixedPatch.operations[0].node.text,formulas[4]);
assert.equal(mixedPatch.operations[1].node.text,formulas[0]);
assert.equal(mixedPatch.recovery.rejected.length,0);
const guarded=guardPatch(patch,[],[]);
const documentBack={id:'document_back',type:'path',d:'M 24 64 L 43 64 Z',fill:'#f8fcff',stroke:'#12172f',strokeWidth:2};
const trailingQuoteSource=JSON.stringify({nodes:[documentBack,...formulaNodes,{...node,id:'literal',text:'strokeWidth:2,"}'}]}).replace('"strokeWidth":2}','"strokeWidth":2,"}');
const trailingQuoteRecovered=recoverBitmapResponse(trailingQuoteSource,'scene');
assert.deepEqual(trailingQuoteRecovered.nodes,[documentBack,...formulaNodes,{...node,id:'literal',text:'strokeWidth:2,"}'}]);
assert.equal(trailingQuoteRecovered.recovery.rejected.length,0);
assert.deepEqual(trailingQuoteRecovered.recovery.repaired,[{reason:'stray quote and trailing comma after number'}]);
assert.equal(recoverBitmapResponse('{"nodes":[{"id":"invalid","strokeWidth":oops,"},'+JSON.stringify(node)+']}','scene').recovery.rejected.length,1);
// Five real candidate cards disappeared because their width had a trailing
// quote. Preserve every supplied value rather than dropping those siblings.
const numericQuoteCards=[121,128,130,130,123].map((w,i)=>({id:'candidate_card_'+i,type:'rect',x:25+i*12,y:153+i*10,w,h:99,radius:9,fill:'#eaf5ff'}));
const numericQuoteSource=JSON.stringify({nodes:[...numericQuoteCards,...formulaNodes,{...node,id:'digits',text:'121, "h":99'}]}).replace(/"w":(121|128|130|123),/g,'"w":$1",');
const numericQuoteRecovered=recoverBitmapResponse(numericQuoteSource,'scene');
assert.deepEqual(numericQuoteRecovered.nodes,[...numericQuoteCards,...formulaNodes,{...node,id:'digits',text:'121, "h":99'}]);
assert.equal(numericQuoteRecovered.recovery.rejected.length,0);
assert.equal(numericQuoteRecovered.recovery.repaired.length,5);
const numericCommaQuoteSource=JSON.stringify({nodes:[...numericQuoteCards,...formulaNodes]}).replace(/"w":(121|128|130|123),/g,'"w":$1,",');
const numericCommaQuoteRecovered=recoverBitmapResponse(numericCommaQuoteSource,'scene');
assert.deepEqual(numericCommaQuoteRecovered.nodes,[...numericQuoteCards,...formulaNodes]);
assert.equal(numericCommaQuoteRecovered.recovery.rejected.length,0);
assert.equal(numericCommaQuoteRecovered.recovery.repaired.length,5);
assert.equal(guarded.operations.length,1);assert.equal(guarded.recovery.rejected.length,1);
const canvas={width:200,height:100};
const transparent={type:'rect',x:0,y:0,w:200,h:100,fill:'none',stroke:'none'};
assert.equal(visibleEditableContent({canvas,nodes:[transparent,{...transparent,fill:'rgba(0,0,0,0)'},{...transparent,fill:'#ffffff'},{...node,opacity:0},{...node,x:300}]}).length,0);
assert.equal(visibleEditableContent({canvas,nodes:[node,{...transparent,fill:'#ff0000',w:10}]}).length,2);
assert.throws(()=>recoverBitmapResponse('{"regions":[{}], bad}','scene'),/regions are metadata/);
console.log('Bitmap schema recovery, malformed siblings, metadata exclusion, patch isolation and visibility: OK');
